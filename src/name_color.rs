pub fn get_color_by_name(name: &str) -> (u8, u8, u8) {
    match name.to_lowercase().as_str() {
        "red" => (255, 0, 0),
        "green" => (0, 255, 0),
        "blue" => (0, 0, 255),
        "white" => (255, 255, 255),
        "yellow" => (255, 255, 0),
        "cyan" => (0, 255, 255),
        "magenta" => (255, 0, 255),
        "orange" => (255, 128, 0),
        "pink" => (255, 0, 127),
        "turquoise" => (0, 128, 128),
        "violet" => (127, 0, 255),
        "lime" => (127, 255, 0),
        "golden" => (255, 180, 50),
        "gray" => (100, 100, 100),
        _ => {
            eprintln!("Unknown color: {}, using white", name);
            (255, 255, 255)
        }
    }
}

pub fn get_color_by_russian_name(name: &str) -> (u8, u8, u8) {
    match name.to_lowercase().as_str() {
        "красный" => (255, 0, 0),
        "зеленый" => (0, 255, 0),
        "синий" => (0, 0, 255),
        "белый" => (255, 255, 255),
        "желтый" => (255, 255, 0),
        "голубой" => (0, 255, 255),
        "пурпурный" => (255, 0, 255),
        "оранжевый" => (255, 128, 0),
        "розовый" => (255, 0, 127),
        "бирюзовый" => (0, 128, 128),
        "фиолетовый" => (127, 0, 255),
        "лаймовый" => (127, 255, 0),
        "золотой" => (255, 180, 50),
        "серый" => (100, 100, 100),
        _ => {
            eprintln!("Неизвестный цвет: {}, используется белый", name);
            (255, 255, 255)
        }
    }
}
